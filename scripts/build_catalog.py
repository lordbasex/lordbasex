def clean(text):
    """Keep raw repository metadata safe inside a Markdown table."""
    text = " ".join(str(text or "").split())
    for old, new in (("\\", "\\\\"), ("|", "\\|"), ("[", "\\["), ("]", "\\]"), ("<", "&lt;"), (">", "&gt;")):
        text = text.replace(old, new)
    return text[:260]


def load_repos():
    token = os.environ.get("GITHUB_TOKEN", "").strip()
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "lordbasex-profile-catalog", "X-GitHub-Api-Version": "2022-11-28"}
    if token:
        headers["Authorization"] = "Bearer " + token
    repos = []
    for page in range(1, 101):
        url = API + "?" + urllib.parse.urlencode({"per_page": 100, "page": page, "sort": "updated", "type": "owner"})
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=25) as resp:
                chunk = json.load(resp)
        except (OSError, ValueError) as exc:
            raise RuntimeError("GitHub API fetch failed: " + str(exc)) from exc
        if not isinstance(chunk, list):
            raise RuntimeError("Unexpected GitHub API response (expected an array)")
        repos.extend(repo for repo in chunk if isinstance(repo, dict) and not repo.get("private", False) and repo.get("owner", {}).get("login", "").lower() == USER)
        if len(chunk) < 100:
            return repos
    raise RuntimeError("GitHub account has more than 10,000 repos; increase max pages")


def render(repos, lang):
    t = I18N[lang]
    groups = [
        (t["projects"], [r for r in repos if not r.get("archived") and not r.get("fork")]),
        (t["forks"], [r for r in repos if not r.get("archived") and r.get("fork")]),
        (t["archived"], [r for r in repos if r.get("archived")]),
    ]
    lines = [f'# {t["title"]}', "", t["intro"], "", f'**{t["total"]}: {len(repos)}**', "", f'[{t["source"]}](https://github.com/{USER}?tab=repositories) | [{t["back"]}](README{("." + lang) if lang != "en" else ""}.md)', "", f'> {t["note"]}', ""]
    for heading, group in groups:
        if not group:
            continue
        lines += [f'## {heading} ({len(group)})', "", f'| {t["name"]} | {t["description"]} | {t["language"]} | {t["stars"]} | {t["updated"]} |', '| --- | --- | --- | ---: | --- |']
        for repo in sorted(group, key=lambda x: (x.get("pushed_at") or "", x.get("name", "").lower()), reverse=True):
            name = clean(repo.get("name") or "unknown")
            url = str(repo.get("html_url") or "")
            if not url.startswith("https://github.com/" + USER + "/"):
                continue
            desc = clean(repo.get("description")) or t["none"]
            language = clean(repo.get("language")) or "-"
            stars = int(repo.get("stargazers_count") or 0)
            date = (repo.get("pushed_at") or "")[:10] or "-"
            lines.append(f'| [{name}]({url}) | {desc} | {language} | {stars} | {date} |')
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    repos = load_repos()
    for lang in I18N:
        path = ROOT / I18N[lang]["file"]
        result = render(repos, lang)
        if not path.exists() or path.read_text("utf-8") != result:
            path.write_text(result, "utf-8")
    print(f"Catalogs refreshed from the GitHub API: {len(repos)} public repositories")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)
